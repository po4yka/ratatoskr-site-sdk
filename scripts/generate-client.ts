import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

// Generates `src/generated/` from two API descriptions, each vendored byte-exact in `openapi/`
// (ADR-0012 of ratatoskr-workspace):
//
// - `content-delivery.json`, the Content Delivery API that `ratatoskr-sites` publishes;
// - `platform.json`, the API of Edge that `ratatoskr-platform` publishes, for the owner routes of
//   a site.
//
// `openapi/<name>.lock.json` records the digest of each file, the commit that it was copied from
// and the generator version. The generation refuses to run when a file and its lock disagree, so
// the output always comes from the pinned descriptions.
//
// Run `node scripts/generate-client.ts` to write `src/generated/`.
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractsLockPath = join(root, 'contracts', 'contracts.lock.json');
const generatorPackagePath = join(root, 'node_modules', 'openapi-typescript', 'package.json');
const contractsUrl = 'https://raw.githubusercontent.com/po4yka/ratatoskr-contracts/';

export const generatedDir = join(root, 'src', 'generated');

// Each description, the repository that publishes it and the key of that commit in its lock.
const descriptions = [
  { name: 'content-delivery', repository: 'ratatoskr-sites', commitKey: 'sitesCommit' },
  { name: 'platform', repository: 'ratatoskr-platform', commitKey: 'platformCommit' },
] as const;

type Description = (typeof descriptions)[number];

const banner = (name: string): string =>
  `// Generated by scripts/generate-client.ts from openapi/${name}.json. Do not edit:\n` +
  `// move the pin in openapi/${name}.lock.json and generate again.\n\n`;

interface DescriptionLock {
  digest: string;
  sitesCommit?: string;
  platformCommit?: string;
  generator: { name: string; version: string };
}

async function readJson<T>(path: string): Promise<T> {
  return JSON.parse(await readFile(path, 'utf8')) as T;
}

async function readPinnedDescription(description: Description): Promise<string> {
  const { name, repository, commitKey } = description;
  const bytes = await readFile(join(root, 'openapi', `${name}.json`));
  const lock = await readJson<DescriptionLock>(join(root, 'openapi', `${name}.lock.json`));
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (digest !== lock.digest) {
    throw new Error(
      `openapi/${name}.json does not match its lock (${repository} ${lock[commitKey]}).\n` +
        `  expected: ${lock.digest}\n  actual:   ${digest}`,
    );
  }
  const generator = await readJson<{ name: string; version: string }>(generatorPackagePath);
  if (generator.name !== lock.generator.name || generator.version !== lock.generator.version) {
    throw new Error(
      `The lock names ${lock.generator.name} ${lock.generator.version}, ` +
        `and ${generator.name} ${generator.version} is installed.`,
    );
  }
  return bytes.toString('utf8');
}

// The description references the contract schemas by raw URLs at one ratatoskr-contracts commit.
// The generator reads the vendored copies under `contracts/` instead, so it needs no network. A
// reference to another commit, or to any other remote file, stops the generation.
function withVendoredContracts(text: string, commit: string): string {
  const local = text.replaceAll(`${contractsUrl}${commit}/`, `${join(root, 'contracts')}/`);
  const remote = /"\$ref":\s*"(https?:[^"]*)"/.exec(local);
  if (remote !== null) {
    throw new Error(
      `The description references ${remote[1]}, which is not a file of the pinned ` +
        `ratatoskr-contracts ${commit} under contracts/.`,
    );
  }
  return local;
}

// Writes the generated types of each description to `outDir`, one file per description.
export async function generateClient(outDir: string): Promise<void> {
  const contracts = await readJson<{ commit: string }>(contractsLockPath);
  await mkdir(outDir, { recursive: true });
  for (const description of descriptions) {
    const text = withVendoredContracts(await readPinnedDescription(description), contracts.commit);
    const ast = await openapiTS(JSON.parse(text) as Parameters<typeof openapiTS>[0]);
    await writeFile(
      join(outDir, `${description.name}.ts`),
      banner(description.name) + astToString(ast),
    );
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateClient(generatedDir);
}
