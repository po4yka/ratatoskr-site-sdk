import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

// Generates `src/generated/` from the Content Delivery API description that `ratatoskr-sites`
// publishes (ADR-0012 of ratatoskr-workspace). The description is vendored byte-exact in
// `openapi/content-delivery.json`, and `openapi/content-delivery.lock.json` records its digest, the
// ratatoskr-sites commit and the generator version. The generation refuses to run when the file and
// the lock disagree, so the output always comes from the pinned description.
//
// Run `node scripts/generate-client.ts` to write `src/generated/`.
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const descriptionPath = join(root, 'openapi', 'content-delivery.json');
const lockPath = join(root, 'openapi', 'content-delivery.lock.json');
const contractsLockPath = join(root, 'contracts', 'contracts.lock.json');
const generatorPackagePath = join(root, 'node_modules', 'openapi-typescript', 'package.json');
const contractsUrl = 'https://raw.githubusercontent.com/po4yka/ratatoskr-contracts/';

export const generatedDir = join(root, 'src', 'generated');
export const generatedFile = 'content-delivery.ts';

const banner =
  '// Generated by scripts/generate-client.ts from openapi/content-delivery.json. Do not edit:\n' +
  '// move the pin in openapi/content-delivery.lock.json and generate again.\n\n';

interface DescriptionLock {
  digest: string;
  sitesCommit: string;
  generator: { name: string; version: string };
}

async function readJson<T>(path: string): Promise<T> {
  return JSON.parse(await readFile(path, 'utf8')) as T;
}

async function readPinnedDescription(): Promise<string> {
  const bytes = await readFile(descriptionPath);
  const lock = await readJson<DescriptionLock>(lockPath);
  const digest = createHash('sha256').update(bytes).digest('hex');
  if (digest !== lock.digest) {
    throw new Error(
      `openapi/content-delivery.json does not match its lock (ratatoskr-sites ${lock.sitesCommit}).\n` +
        `  expected: ${lock.digest}\n  actual:   ${digest}`,
    );
  }
  const generator = await readJson<{ name: string; version: string }>(generatorPackagePath);
  if (generator.name !== lock.generator.name || generator.version !== lock.generator.version) {
    throw new Error(
      `The lock names ${lock.generator.name} ${lock.generator.version}, ` +
        `and ${generator.name} ${generator.version} is installed.`,
    );
  }
  return bytes.toString('utf8');
}

// The description references the contract schemas by raw URLs at one ratatoskr-contracts commit.
// The generator reads the vendored copies under `contracts/` instead, so it needs no network. A
// reference to another commit, or to any other remote file, stops the generation.
function withVendoredContracts(text: string, commit: string): string {
  const local = text.replaceAll(`${contractsUrl}${commit}/`, `${join(root, 'contracts')}/`);
  const remote = /"\$ref":\s*"(https?:[^"]*)"/.exec(local);
  if (remote !== null) {
    throw new Error(
      `The description references ${remote[1]}, which is not a file of the pinned ` +
        `ratatoskr-contracts ${commit} under contracts/.`,
    );
  }
  return local;
}

// Writes the generated client to `outDir`.
export async function generateClient(outDir: string): Promise<void> {
  const contracts = await readJson<{ commit: string }>(contractsLockPath);
  const description = withVendoredContracts(await readPinnedDescription(), contracts.commit);
  const ast = await openapiTS(JSON.parse(description) as Parameters<typeof openapiTS>[0]);
  await mkdir(outDir, { recursive: true });
  await writeFile(join(outDir, generatedFile), banner + astToString(ast));
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateClient(generatedDir);
}
